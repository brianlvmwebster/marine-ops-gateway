CREATE TABLE IF NOT EXISTS oauth_accounts (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 provider text NOT NULL, provider_user_id text NOT NULL, provider_email text,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(provider,provider_user_id),
 CONSTRAINT gateway_company_microsoft_tenant CHECK(provider <> 'microsoft' OR provider_user_id LIKE '5b007bab-2109-468d-ac89-c12281d41515:%')
);
CREATE TABLE IF NOT EXISTS native_gateway_members (
 email text PRIMARY KEY CHECK(email=lower(email)),
 role text NOT NULL CHECK(role IN ('admin','user')), enabled boolean NOT NULL DEFAULT true,
 source_user_id text, service_user_id text UNIQUE, auth_user_id integer UNIQUE REFERENCES users(id),
 version integer NOT NULL DEFAULT 1, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS native_gateway_links (
 id integer PRIMARY KEY CHECK(id=1), contents jsonb NOT NULL CHECK(jsonb_typeof(contents)='array'),
 version integer NOT NULL DEFAULT 1, updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS native_gateway_assets (
 id uuid PRIMARY KEY, filename text UNIQUE NOT NULL, temporary_filename text NOT NULL,
 content_type text NOT NULL CHECK(content_type IN ('image/png','image/jpeg','image/webp')),
 expected_size integer NOT NULL CHECK(expected_size BETWEEN 1 AND 2097152),
 owner_user_id text NOT NULL, ready boolean NOT NULL DEFAULT false, created_at timestamptz NOT NULL DEFAULT now()
);
-- Destination contents and member identities are migrated privately, never committed.
