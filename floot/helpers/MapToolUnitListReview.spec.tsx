import React from "react";
import {render,fireEvent,screen,within,cleanup,act,waitFor} from "@testing-library/react";
import {QueryClient,QueryClientProvider} from "@tanstack/react-query";
import superjson from "superjson";
import MappingUtility from "../components/MapToolWorkspace";
import type {Space,StorageMap} from "../endpoints/mapping/maps_GET.schema";
describe("linked unit list and image dots",()=>{
 let client:QueryClient,resize:typeof ResizeObserver;
 const viewport=Object.getOwnPropertyDescriptor(window,"innerWidth");
 const nativeEvents={Event:globalThis.Event,CustomEvent:globalThis.CustomEvent};
 beforeEach(()=>{
  Object.assign(globalThis,{Event:window.Event,CustomEvent:window.CustomEvent});
  resize=globalThis.ResizeObserver;
  globalThis.ResizeObserver=class implements ResizeObserver{constructor(_callback:ResizeObserverCallback){}observe(){}unobserve(){}disconnect(){}};
 });
 afterEach(()=>{cleanup();client?.clear();globalThis.ResizeObserver=resize;Object.assign(globalThis,nativeEvents);if(viewport)Object.defineProperty(window,"innerWidth",viewport);});
 it("links hover and selection in both views, edits the same records, filters and keeps markers text-free",()=>{
  try{
   const unit=(n:number):Space=>({id:"a543732b-173e-46fc-abaf-bafcb6e038c"+n,label:"U-"+n,points:[],marker:{x:.4+n*.005,y:.5},lastName:n===1?"Webster":"Jones",firstName:n===1?"Brian":"Jo",boatDescription:n===1?"Blue pontoon":"White boat",trailerDetails:n===1?"Tandem trailer":"",notes:"",status:"occupied",reviewed:n===1});
   const map:StorageMap={id:"b543732b-173e-46fc-abaf-bafcb6e038ca",name:"List test",imageUrl:"/test.png",imageWidth:1000,imageHeight:650,sourceKind:"aerial",revision:1,spaces:[unit(1),unit(2)]};
   client=new QueryClient({defaultOptions:{queries:{retry:false},mutations:{retry:false}}});
   client.setQueryData(["storage-maps"],{maps:[map]});
   const network=spyOn(globalThis,"fetch").and.rejectWith(new Error("Unexpected network request"));
   render(<QueryClientProvider client={client}><MappingUtility/></QueryClientProvider>);
   fireEvent.click(screen.getByRole("button",{name:"Unit list"}));
   let list=screen.getByRole("region",{name:"Unit list"}),rows=within(list);
   for(const heading of ["Last Name","First Name","Boat","Trailer"])expect(rows.getByRole("columnheader",{name:heading})).toBeTruthy();
   const row=list.querySelector('tr[data-unit-id="'+map.spaces[0].id+'"]')!;
   const marker=screen.getByRole("button",{name:/^Location U-1:/});
   expect(marker.textContent).toBe("");
   expect(marker.hasAttribute("title")).toBe(false);
   fireEvent.pointerEnter(row);
   expect(marker.getAttribute("data-highlighted")).toBe("true");
   fireEvent.pointerLeave(row);
   fireEvent.pointerEnter(marker);
   expect(row.getAttribute("data-highlighted")).toBe("true");
   fireEvent.pointerLeave(marker);
   fireEvent.click(rows.getByRole("button",{name:"Edit unit U-1"}));
   expect((screen.getByLabelText("Last Name") as HTMLInputElement).value).toBe("Webster");
   fireEvent.change(screen.getByLabelText("Last Name"),{target:{value:"Updated"}});
   fireEvent.change(screen.getByLabelText("Boat description"),{target:{value:"Edited boat"}});
   fireEvent.change(screen.getByLabelText("Trailer details (if applicable)"),{target:{value:"Edited trailer"}});
   expect((rows.getByLabelText("Last Name for U-1") as HTMLInputElement).value).toBe("Updated");expect((rows.getByLabelText("Boat for U-1") as HTMLInputElement).value).toBe("Edited boat");expect((rows.getByLabelText("Trailer for U-1") as HTMLInputElement).value).toBe("Edited trailer");
   fireEvent.change(rows.getByLabelText("Search unit list"),{target:{value:"Edited trailer"}});
   expect(rows.queryByRole("button",{name:"Edit unit U-2"})).toBeNull();
   fireEvent.click(screen.getByRole("button",{name:"Full image"}));
   const dialog=screen.getByRole("dialog"),ui=within(dialog);
   fireEvent.click(ui.getByRole("button",{name:"Unit list"}));
   list=ui.getByRole("region",{name:"Unit list"});rows=within(list);
   Object.defineProperty(window,"innerWidth",{configurable:true,value:393,writable:true});
   fireEvent.click(rows.getByRole("button",{name:"Edit unit U-2"}));
   expect(rows.getByRole("button",{name:"Expand unit list"})).toBeTruthy();
   expect((ui.getByLabelText("Last Name") as HTMLInputElement).value).toBe("Jones");
   expect(document.activeElement).toBe(ui.getByLabelText("Last Name"));
   fireEvent.change(ui.getByLabelText("First Name"),{target:{value:"Joseph"}});
   expect((rows.getByLabelText("First Name for U-2") as HTMLInputElement).value).toBe("Joseph");
   const modalMarker=ui.getByRole("button",{name:/^Location U-2:/});
   fireEvent.pointerEnter(modalMarker);
   expect(list.querySelector('tr[data-unit-id="'+map.spaces[1].id+'"]')?.getAttribute("data-highlighted")).toBe("true");
   expect(modalMarker.textContent).toBe("");
   fireEvent.click(rows.getByRole("button",{name:"Expand unit list"}));
   expect(rows.getByRole("button",{name:"Edit unit U-2"})).toBeTruthy();
   fireEvent.click(rows.getByRole("button",{name:"Close unit list"}));
   expect(ui.queryByRole("region",{name:"Unit list"})).toBeNull();
   expect(screen.getByRole("dialog")).toBe(dialog);
   expect(network).not.toHaveBeenCalled();
  }catch(e){throw new Error(JSON.stringify(e instanceof AggregateError?e.errors.map(x=>String(x)):String(e)));}
 });
 it("edits all four columns without opening details and saves the shared draft from the modal",async()=>{
  try{
   const first:Space={id:"a543732b-173e-46fc-abaf-bafcb6e038c1",label:"U-1",points:[],marker:{x:.4,y:.5},lastName:"Webster",firstName:"Brian",boatDescription:"Blue pontoon",trailerDetails:"Tandem",notes:"Keep notes",status:"occupied",reviewed:true};
   const second:Space={...first,id:"a543732b-173e-46fc-abaf-bafcb6e038c2",label:"U-2",marker:{x:.6,y:.5},lastName:"Jones",reviewed:false};
   const map:StorageMap={id:"b543732b-173e-46fc-abaf-bafcb6e038ca",name:"Inline test",imageUrl:"/test.png",imageWidth:1000,imageHeight:650,sourceKind:"aerial",revision:1,spaces:[first,second]};
   client=new QueryClient({defaultOptions:{queries:{retry:false},mutations:{retry:false}}});client.setQueryData(["storage-maps"],{maps:[map]});
   const candidate:Space={...second,id:"a543732b-173e-46fc-abaf-bafcb6e038c3",label:"U-3",marker:{x:.85,y:.8},lastName:"",firstName:"",boatDescription:"Detected boat",trailerDetails:""};
   const payloads:{spaces:Space[];revision:number}[]=[];let finish:((r:Response)=>void)|undefined;
   spyOn(globalThis,"fetch").and.callFake(async(url,init)=>{if(String(url).includes("/analyze"))return new Response(superjson.stringify({spaces:[candidate],message:"Mock detection"}));payloads.push(superjson.parse(String(init?.body)));return new Promise<Response>(resolve=>{finish=resolve;});});
   render(<QueryClientProvider client={client}><MappingUtility/></QueryClientProvider>);
   fireEvent.click(screen.getByRole("button",{name:"Unit list"}));
   let list=screen.getByRole("region",{name:"Unit list"}),rows=within(list);
   const values=[["Last Name","Changed"],["First Name","Chris"],["Boat","Red boat"],["Trailer","Single axle"]];
   for(const [field,value] of values){
    const input=rows.getByLabelText(field+" for U-1");
    fireEvent.click(input);fireEvent.change(input,{target:{value}});
   }
   expect(screen.getByRole("button",{name:"Expand unit details sidebar"})).toBeTruthy();
   expect(screen.queryByLabelText("Unit label")).toBeNull();
   expect(screen.getByRole("button",{name:/^Location U-1: Changed, Chris/})).toBeTruthy();
   fireEvent.keyDown(rows.getByLabelText("Last Name for U-1"),{key:"Enter"});
   expect(payloads.length).toBe(0);
   fireEvent.change(rows.getByLabelText("Search unit list"),{target:{value:"Changed"}});
   const name=rows.getByLabelText("Last Name for U-1") as HTMLInputElement,next=rows.getByLabelText("First Name for U-1");
   act(()=>name.focus());fireEvent.change(name,{target:{value:"Outside filter"}});
   expect(rows.getByLabelText("Last Name for U-1")).toBe(name);
   act(()=>next.focus());
   expect(rows.getByLabelText("Last Name for U-1")).toBe(name);
   act(()=>(rows.getByLabelText("Search unit list") as HTMLInputElement).focus());
   expect(rows.queryByLabelText("Last Name for U-1")).toBeNull();
   fireEvent.change(rows.getByLabelText("Search unit list"),{target:{value:""}});
   fireEvent.click(screen.getByRole("button",{name:"Full image"}));
   const dialog=screen.getByRole("dialog"),ui=within(dialog);
   fireEvent.click(ui.getByRole("button",{name:"Unit list"}));
   list=ui.getByRole("region",{name:"Unit list"});rows=within(list);
   Object.defineProperty(window,"innerWidth",{configurable:true,value:393,writable:true});
   const modalName=rows.getByLabelText("Last Name for U-1");act(()=>(modalName as HTMLInputElement).focus());fireEvent.click(modalName);
   fireEvent.change(modalName,{target:{value:"Modal name"}});
   fireEvent.change(rows.getByLabelText("First Name for U-2"),{target:{value:"Other boat"}});
   expect(rows.getByRole("button",{name:"Minimize unit list"})).toBeTruthy();
   expect(ui.queryByLabelText("Unit label")).toBeNull();
   expect(ui.getByRole("button",{name:/^Location U-1: Modal name, Chris/})).toBeTruthy();
   expect((rows.getByLabelText("Last Name for U-1") as HTMLInputElement).maxLength).toBe(100);
   expect((rows.getByLabelText("Boat for U-1") as HTMLInputElement).maxLength).toBe(500);
   fireEvent.click(ui.getByRole("button",{name:"Save map"}));
   await waitFor(()=>{if(payloads.length!==1)throw new Error("Waiting for save");});
   expect((rows.getByLabelText("Last Name for U-1") as HTMLInputElement).disabled).toBe(true);
   expect(payloads[0].spaces[0]).toEqual({...first,lastName:"Modal name",firstName:"Chris",boatDescription:"Red boat",trailerDetails:"Single axle"});
   expect(payloads[0].spaces[1]).toEqual({...second,firstName:"Other boat"});
   await act(async()=>finish!(new Response(superjson.stringify({id:map.id,revision:2}))));
   await waitFor(()=>{if((rows.getByLabelText("Last Name for U-1") as HTMLInputElement).disabled)throw new Error("Waiting for saved state");});
   expect(ui.getByText("All changes saved")).toBeTruthy();
   expect(screen.getByRole("dialog")).toBe(dialog);
   expect(ui.queryByLabelText("Unit label")).toBeNull();
   fireEvent.click(ui.getByRole("button",{name:"Detect"}));
   fireEvent.click(ui.getByRole("button",{name:"Detect full image"}));
   await waitFor(()=>{rows.getByLabelText("Last Name for U-3");});
   const suggested=rows.getByLabelText("Last Name for U-3") as HTMLInputElement;
   act(()=>suggested.focus());fireEvent.change(suggested,{target:{value:"New owner"}});
   expect(rows.getByLabelText("Last Name for U-3")).toBe(suggested);
   expect(document.activeElement).toBe(suggested);
   expect((rows.getByLabelText("Last Name for U-1") as HTMLInputElement).value).toBe("Modal name");
   expect(ui.queryByLabelText("Unit label")).toBeNull();
   fireEvent.click(ui.getByRole("button",{name:"Save map"}));
   await waitFor(()=>{if(payloads.length!==2)throw new Error("Waiting for candidate save");});
   expect(payloads[1].spaces.length).toBe(3);
   expect(payloads[1].spaces[0]).toEqual(payloads[0].spaces[0]);
   expect(payloads[1].spaces[2]).toEqual({...candidate,lastName:"New owner"});
   await act(async()=>finish!(new Response(superjson.stringify({id:map.id,revision:3}))));
  }catch(e){throw new Error(JSON.stringify(e instanceof AggregateError?e.errors.map(x=>String(x)):String(e)));}
 });

});