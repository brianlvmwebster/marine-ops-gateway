import React from "react";
import {render,fireEvent,screen,within,waitFor,cleanup,act} from "@testing-library/react";
import {QueryClient,QueryClientProvider} from "@tanstack/react-query";
import superjson from "superjson";
import MappingUtility from "../components/MapToolWorkspace";
import type {Space,StorageMap} from "../endpoints/mapping/maps_GET.schema";

describe("save reviewed boat and advance",()=>{
 let resize:typeof ResizeObserver,client:QueryClient;
 const nativeEvents={Event:globalThis.Event,CustomEvent:globalThis.CustomEvent};
 beforeEach(()=>{
  globalThis.Event=window.Event;globalThis.CustomEvent=window.CustomEvent;
  resize=globalThis.ResizeObserver;
  globalThis.ResizeObserver=class implements ResizeObserver{constructor(_callback:ResizeObserverCallback){}observe(){}unobserve(){}disconnect(){}};
 });
 afterEach(()=>{cleanup();client?.clear();globalThis.ResizeObserver=resize;Object.assign(globalThis,nativeEvents);});
 it("saves the latest name once, waits before advancing, retains failures, and finishes in the modal",async()=>{
  try{
  const boat=(n:number,reviewed=false):Space=>({id:"a543732b-173e-46fc-abaf-bafcb6e038c"+n,label:"B-"+n,points:[],marker:{x:n/4,y:.5},firstName:"",lastName:"",boatDescription:"Boat",trailerDetails:"",notes:"",status:"occupied",reviewed});
  const map:StorageMap={id:"b543732b-173e-46fc-abaf-bafcb6e038ca",name:"Review test",imageUrl:"/test.png",imageWidth:1000,imageHeight:650,sourceKind:"aerial",revision:1,spaces:[boat(1,true),boat(2),boat(3)]};
  client=new QueryClient({defaultOptions:{queries:{retry:false},mutations:{retry:false}}});
  client.setQueryData(["storage-maps"],{maps:[map]});
  const payloads:any[]=[];let finish:((r:Response)=>void)|undefined;
  spyOn(globalThis,"fetch").and.callFake(async(_input,init)=>{
   payloads.push(superjson.parse(String(init?.body)));
   return new Promise<Response>(resolve=>{finish=resolve;});
  });
  try{render(<QueryClientProvider client={client}><MappingUtility/></QueryClientProvider>);}catch(e){throw new Error(JSON.stringify(e instanceof AggregateError?e.errors.map(x=>String(x)):String(e)));}
  fireEvent.click(screen.getByRole("button",{name:"Full image"}));
  const dialog=screen.getByRole("dialog"),ui=within(dialog);
  expect((ui.getByRole("button",{name:"Previous boat"}) as HTMLButtonElement).disabled).toBe(true);
  expect((ui.getByRole("button",{name:"Next boat"}) as HTMLButtonElement).disabled).toBe(true);
  fireEvent.click(ui.getByRole("button",{name:"Next unreviewed boat"}));
  expect((ui.getByLabelText("Unit label") as HTMLInputElement).value).toBe("B-2");
  expect(document.activeElement).toBe(ui.getByLabelText("Last Name"));
  fireEvent.change(ui.getByLabelText("Last Name"),{target:{value:"Webster"}});
  fireEvent.change(ui.getByLabelText("First Name"),{target:{value:"Brian"}});
  const advance=ui.getByRole("button",{name:"Mark reviewed and next"});
  fireEvent.keyDown(ui.getByLabelText("Last Name"),{key:"Enter",isComposing:true});
  fireEvent.keyDown(ui.getByLabelText("Last Name"),{key:"Enter",repeat:true});
  fireEvent.keyDown(ui.getByLabelText("First Name"),{key:"Enter",shiftKey:true});
  fireEvent.keyDown(ui.getByLabelText("Notes"),{key:"Enter"});
  fireEvent.keyDown(ui.getByLabelText("Boat description"),{key:"Enter"});
  expect(payloads.length).toBe(0);
  fireEvent.keyDown(ui.getByLabelText("First Name"),{key:"Enter"});
  fireEvent.click(advance);
  await waitFor(()=>{if(payloads.length!==1)throw new Error("Waiting for save 1");});
  expect(payloads[0].spaces[1].lastName).toBe("Webster");
  expect(payloads[0].spaces[1].firstName).toBe("Brian");
  expect(payloads[0].spaces[1].reviewed).toBe(true);
  expect((ui.getByLabelText("Unit label") as HTMLInputElement).value).toBe("B-2");
  fireEvent.keyDown(dialog,{key:"ArrowLeft",altKey:true});
  expect((ui.getByLabelText("Unit label") as HTMLInputElement).value).toBe("B-2");
  await act(async()=>finish!(new Response(superjson.stringify({id:map.id,revision:2}))));
  await waitFor(()=>{if((ui.getByLabelText("Unit label") as HTMLInputElement).value!=="B-3")throw new Error("Waiting for next boat");});
  expect(screen.getByRole("dialog")).toBe(dialog);
  expect(document.activeElement).toBe(ui.getByLabelText("Last Name"));
  fireEvent.change(ui.getByLabelText("Notes"),{target:{value:"Keep my place"}});
  fireEvent.keyDown(ui.getByLabelText("Last Name"),{key:"ArrowLeft"});
  fireEvent.keyDown(ui.getByLabelText("Last Name"),{key:"ArrowLeft",ctrlKey:true});
  fireEvent.keyDown(ui.getByLabelText("Last Name"),{key:"ArrowLeft",altKey:true,ctrlKey:true});
  fireEvent.keyDown(ui.getByLabelText("Last Name"),{key:"ArrowLeft",altKey:true,isComposing:true});
  fireEvent.keyDown(ui.getByLabelText("Last Name"),{key:"ArrowLeft",altKey:true,repeat:true});
  expect((ui.getByLabelText("Unit label") as HTMLInputElement).value).toBe("B-3");
  expect(fireEvent.keyDown(ui.getByLabelText("Last Name"),{key:"ArrowLeft",altKey:true})).toBe(false);
  expect((ui.getByLabelText("Unit label") as HTMLInputElement).value).toBe("B-2");
  expect((ui.getByLabelText("Last Name") as HTMLInputElement).value).toBe("Webster");
  expect(document.activeElement).toBe(ui.getByLabelText("Last Name"));
  expect((ui.getByRole("button",{name:"Previous boat"}) as HTMLButtonElement).disabled).toBe(true);
  fireEvent.change(ui.getByLabelText("Last Name"),{target:{value:"Corrected"}});
  const marker=ui.getByRole("button",{name:/^Location B-2:/});
  fireEvent.keyDown(marker,{key:"ArrowRight"});
  fireEvent.click(ui.getByRole("button",{name:"Mark reviewed"}));
  expect(payloads.length).toBe(1);
  fireEvent.click(ui.getByRole("button",{name:"Next unreviewed boat"}));
  expect((ui.getByLabelText("Unit label") as HTMLInputElement).value).toBe("B-3");
  expect((ui.getByLabelText("Notes") as HTMLTextAreaElement).value).toBe("Keep my place");
  fireEvent.change(ui.getByLabelText("Last Name"),{target:{value:"Retained"}});
  fireEvent.keyDown(ui.getByLabelText("Last Name"),{key:"Enter"});
  await waitFor(()=>{if(payloads.length!==2)throw new Error("Waiting for save 2");});
  expect(payloads[1].revision).toBe(2);
  expect(payloads[1].spaces[1].lastName).toBe("Corrected");
  expect(payloads[1].spaces[1].marker.x).toBeCloseTo(.502,5);
  await act(async()=>finish!(new Response(superjson.stringify({error:"Save failed"}),{status:409})));
  await waitFor(()=>{if((ui.getByRole("button",{name:"Mark reviewed and next"}) as HTMLButtonElement).disabled)throw new Error("Waiting for failed save");});
  expect((ui.getByLabelText("Unit label") as HTMLInputElement).value).toBe("B-3");
  expect((ui.getByLabelText("Last Name") as HTMLInputElement).value).toBe("Retained");
  expect(ui.getByText("Unsaved changes")).toBeTruthy();
  fireEvent.click(ui.getByRole("button",{name:"Mark reviewed and next"}));
  await waitFor(()=>{if(payloads.length!==3)throw new Error("Waiting for save 3");});
  expect(payloads[2].revision).toBe(2);
  await act(async()=>finish!(new Response(superjson.stringify({id:map.id,revision:3}))));
  await waitFor(()=>expect(ui.getByText("All changes saved")).toBeTruthy());
  expect(ui.getByText("All boats reviewed")).toBeTruthy();
  expect((ui.getByRole("button",{name:"Next unreviewed boat"}) as HTMLButtonElement).disabled).toBe(true);
  expect((ui.getByLabelText("Unit label") as HTMLInputElement).value).toBe("B-3");
  expect(screen.getByRole("dialog")).toBe(dialog);
  fireEvent.click(ui.getByRole("button",{name:"Previous boat"}));
  expect((ui.getByLabelText("Unit label") as HTMLInputElement).value).toBe("B-2");
  expect((ui.getByLabelText("Last Name") as HTMLInputElement).value).toBe("Corrected");
  expect(payloads.length).toBe(3);
  fireEvent.change(ui.getByLabelText("First Name"),{target:{value:"Forward edit"}});
  expect(ui.getByRole("button",{name:"Previous boat"}).getAttribute("aria-keyshortcuts")).toBe("Alt+ArrowLeft");
  expect(ui.getByRole("button",{name:"Next boat"}).getAttribute("aria-keyshortcuts")).toBe("Alt+ArrowRight");
  fireEvent.keyDown(ui.getByLabelText("First Name"),{key:"ArrowRight",altKey:true});
  expect((ui.getByLabelText("Unit label") as HTMLInputElement).value).toBe("B-3");
  expect((ui.getByLabelText("Last Name") as HTMLInputElement).value).toBe("Retained");
  expect((ui.getByRole("button",{name:"Next boat"}) as HTMLButtonElement).disabled).toBe(true);
  expect(document.activeElement).toBe(ui.getByLabelText("Last Name"));
  fireEvent.click(ui.getByRole("button",{name:"Previous boat"}));
  expect((ui.getByLabelText("First Name") as HTMLInputElement).value).toBe("Forward edit");
  expect((ui.getByRole("button",{name:"Next boat"}) as HTMLButtonElement).disabled).toBe(false);
  expect(payloads.length).toBe(3);
  fireEvent.click(ui.getByRole("button",{name:/^Location B-3:/}));
  fireEvent.click(ui.getByRole("button",{name:/^Location B-2:/}));
  fireEvent.click(ui.getByRole("button",{name:/^Location B-1:/}));
  fireEvent.click(ui.getByRole("button",{name:"Previous boat"}));
  expect((ui.getByLabelText("Unit label") as HTMLInputElement).value).toBe("B-2");
  fireEvent.click(ui.getByRole("button",{name:"Remove selected marker"}));
  fireEvent.click(ui.getByRole("button",{name:"Previous boat"}));
  expect((ui.getByLabelText("Unit label") as HTMLInputElement).value).toBe("B-3");
  fireEvent.click(ui.getByRole("button",{name:"Next boat"}));
  expect((ui.getByLabelText("Unit label") as HTMLInputElement).value).toBe("B-1");
  expect((ui.getByRole("button",{name:"Next boat"}) as HTMLButtonElement).disabled).toBe(true);
  expect(screen.getByRole("dialog")).toBe(dialog);
  expect(payloads.length).toBe(3);
  const finalMarker=ui.getByRole("button",{name:/^Location B-1:/});
  fireEvent.keyDown(finalMarker,{key:"ArrowLeft",altKey:true});
  expect((ui.getByLabelText("Unit label") as HTMLInputElement).value).toBe("B-3");
  fireEvent.keyDown(ui.getByLabelText("Last Name"),{key:"ArrowRight",altKey:true});
  expect((ui.getByLabelText("Unit label") as HTMLInputElement).value).toBe("B-1");
  expect(ui.getByRole("button",{name:/^Location B-1:/}).getAttribute("style")).toContain("left: 25%");
  expect(fireEvent.keyDown(ui.getByLabelText("Last Name"),{key:"ArrowRight",altKey:true})).toBe(false);
  expect((ui.getByLabelText("Unit label") as HTMLInputElement).value).toBe("B-1");
  }catch(e){throw new Error(JSON.stringify(e instanceof AggregateError?e.errors.map(x=>String(x)):String(e)));}
 });
});
